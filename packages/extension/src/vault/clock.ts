/**
 * 时钟接缝 —— 会话超时**只能靠读时间**，不能靠定时器。
 *
 * 这不是为了「方便测试」才抽象出来的（那是副产品）。真正的原因在 MV3：
 *
 *   1. **Service worker 会被杀掉。** Chrome 在约 30 秒空闲后终止它。
 *      `setTimeout` 挂着的那一刻进程可能已经不存在了，回调永远不会执行 ——
 *      于是「用定时器把密钥清掉」在 MV3 里是一个**会静默失效**的实现：
 *      本地怎么测都是对的，装进浏览器就变成「密钥一直留在内存里」。
 *   2. **即使定时器活着，它也只是通知。** 真正决定「现在能不能解密」的判据
 *      必须是读出时间后比较一次（`session.ts` 里的惰性过期）。定时器最多
 *      是个提前量，而提前量丢了不影响正确性。
 *
 * 所以本层对时间只有一个要求：**给我一个「现在几点」**。
 * 传进来之后，超时行为就变成完全确定的 —— 测试里把表往前拨 16 分钟即可，
 * 不需要等待、不需要 fake timer、也不会因为机器负载而闪断。
 *
 * 顺带一提：本包的 `tsconfig` 继承 `lib: ["ES2023"]` + `types: []`，
 * 因此 `setTimeout` / `setInterval` **在编译期就不存在**。
 * 「用定时器实现 TTL」这条错误路线在这里不是被禁止，而是不可写 ——
 * 与红线 1 / 红线 6 的处理方式一样。
 */

export interface Clock {
  /** 当前时刻的毫秒时间戳（与 `Date.now()` 同一个基准）。 */
  now(): number
}

/** 生产用的时钟。扩展端直接用它，只有测试会换掉。 */
export const systemClock: Clock = {
  now: () => Date.now(),
}
